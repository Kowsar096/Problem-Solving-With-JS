const fruits = ['Apple', 'Banana', 'Orange', 'Watermelon'];
console.log('----For Loop----')
for (let i = 0; i< fruits.length; i++) {
    // console.log(i);
    console.log(fruits[i]);
}

console.log('----While Loop----')

let k = 0;
 while (k < fruits.length){
    console.log(fruits[k]);
    k++;
 }